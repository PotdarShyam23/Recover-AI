
// gemini key and all info
function getGeminiConfig() {
  const apiKey = process.env.GEMINI_API_KEY || process.env.GOOGLE_API_KEY;
  const model = process.env.GEMINI_MODEL || 'gemini-1.5-flash';
  return { apiKey, model };
}
// clear all json text remove parse not needed spoace so DB dont give the errror
function cleanJsonText(rawText) {
  return String(rawText || '')
    .replace(/^```json\s*/i, '')
    .replace(/^```\s*/i, '')
    .replace(/```$/i, '')
    .trim();
}

function parseGeminiJson(rawText) {
  const cleaned = cleanJsonText(rawText);
  try {
    return JSON.parse(cleaned);
  } catch {
    const firstBrace = cleaned.indexOf('{');
    const lastBrace = cleaned.lastIndexOf('}');
    if (firstBrace >= 0 && lastBrace > firstBrace) {
      try {
        // after removing all the braces
        return JSON.parse(cleaned.slice(firstBrace, lastBrace + 1));
      } catch {
        return null;
      }
    }
    return null;
  }
}

async function callGemini(systemPrompt, userPrompt) {
  const { apiKey, model } = getGeminiConfig();
  if (!apiKey || apiKey === 'your_gemini_api_key_here') {
    return null; // Graceful fallback
  }

  const startTime = Date.now();
  console.log(`\n[Gemini AI] 🧠 Calling Google Generative Language API (${model})...`);

  try {
    const response = await fetch(
      `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${apiKey}`,
      {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          contents: [
            {
              role: 'user',
              parts: [{ text: `${systemPrompt}\n\nTask context:\n${userPrompt}` }]
            }
          ],
          generationConfig: {
            temperature: 0.3,
            responseMimeType: 'application/json'
          }
        })
      }
    );

    const latencyMs = Date.now() - startTime;

    if (!response.ok) {
      console.warn(`[Gemini AI] ⚠️ API returned status ${response.status} ${response.statusText}`);
      return null;
    }

    const payload = await response.json();
    const text = payload?.candidates?.[0]?.content?.parts?.[0]?.text;
    const parsed = parseGeminiJson(text);

    if (parsed) {
      parsed._aiSource = 'GEMINI_LIVE_API';
      parsed._model = model;
      parsed._latencyMs = latencyMs;
      console.log(`[Gemini AI] ✨ Live response generated by ${model} in ${latencyMs}ms!`);
    }

    return parsed;
  } catch (err) {
    console.error(`[Gemini AI] ❌ Connection error:`, err.message);
    return null;
  }
}

/**
 * AGENT 1: RECOVERY STRATEGY & ACTION AGENT
 * Evaluates the failure context dynamically (without hardcoding amounts or static rules)
 * and determines whether it's recoverable, what channel to initiate, and the progression sequence.
 */
export async function decideRecoveryStrategy(context) {
  const systemPrompt = `
    You are the Senior Recovery Strategy Agent for RecoverAI, an intelligent merchant-side revenue recovery platform.
    Your goal is to decide the next best merchant recovery intervention for an incomplete or failed payment.
    CRITICAL RULES:
    1. Do not diagnose technical gateway mechanics. Focus on customer re-engagement and revenue recovery.
    2. Assess if this failure is actually recoverable by the merchant (e.g. drop-offs, timing issues, card renewals are recoverable; active fraud/stolen cards are unrecoverable).
    3. Choose a single immediate next action: 'whatsapp', 'sms', 'voice', 'wait', or 'stop'.
    4. Provide a logical channel sequence (e.g., ['whatsapp', 'voice'] or ['sms', 'whatsapp', 'voice']).
    5. Return strict JSON with:
       - "isRecoverable": boolean,
       - "action": string ('whatsapp' | 'sms' | 'voice' | 'wait' | 'stop'),
       - "reason": string (clear merchant-facing explanation of strategy),
       - "confidence": number (between 0.0 and 1.0),
       - "channelSequence": array of strings,
       - "recommendedDelayHours": number
  `;

  const userPrompt = JSON.stringify(context, null, 2);
  // send to LLM
  const aiResult = await callGemini(systemPrompt, userPrompt);

  if (aiResult && aiResult.action) {
    return aiResult;
  }

  // Dynamic Heuristic Fallback (when GEMINI_API_KEY is not configured)(genric failure)

  // now by any reason netrowrk gemini server app dont crash it create some fallback if LLM give response then no need otheriwse it can use
  const isFatalError = /fraud|stolen|lost_card|blacklisted/i.test(context.errorCode || '') ||
                       /fraud|stolen/i.test(context.errorDescription || '');

  if (isFatalError) {
    return {
      isRecoverable: false,
      action: 'stop',
      reason: 'Payment flagged with risk/fraud indicators by payment gateway. Merchant recovery outreach halted for security.',
      confidence: 0.95,
      channelSequence: ['stop'],
      recommendedDelayHours: 0
    };
  }

  // If customer has an active promise, schedule or wait
  if (context.hasActivePromise) {
    return {
      isRecoverable: true,
      action: 'wait',
      reason: 'Customer has committed to a promise-to-pay date. Awaiting promised settlement date before further outreach.',
      confidence: 0.92,
      channelSequence: ['whatsapp', 'voice'],
      recommendedDelayHours: 24
    };
  }

  // Progression based on attempt history
  if (context.attemptCount === 0) {
    return {
      isRecoverable: true,
      action: context.customerPreferredChannel || 'whatsapp',
      reason: 'Initial incomplete payment detected. Initiating non-intrusive re-engagement with one-click recovery link.',
      confidence: 0.88,
      channelSequence: ['whatsapp', 'sms', 'voice'],
      recommendedDelayHours: 0
    };
  }

  if (context.messageAttempts >= 1 && context.voiceAttempts === 0) {
    return {
      isRecoverable: true,
      action: 'voice',
      reason: 'Previous digital message received no conversion. Escalating to Hinglish AI Voice Agent for conversational recovery.',
      confidence: 0.84,
      channelSequence: ['voice', 'stop'],
      recommendedDelayHours: 4
    };
  }

  if (context.attemptCount >= 3 || context.voiceAttempts >= 1) {
    return {
      isRecoverable: false,
      action: 'stop',
      reason: 'Outreach quota exhausted without customer settlement. Recovery stopped to respect customer communication limits.',
      confidence: 0.91,
      channelSequence: ['stop'],
      recommendedDelayHours: 0
    };
  }

  return {
    isRecoverable: true,
    action: 'whatsapp',
    reason: 'Follow-up re-engagement scheduled with refreshed recovery options.',
    confidence: 0.8,
    channelSequence: ['whatsapp', 'voice'],
    recommendedDelayHours: 6
  };
}

/**
 * AGENT 2: DYNAMIC OUTREACH MESSAGE GENERATOR
 * Generates situation-aware, personalized recovery copy with payment links.
 */
export async function generateOutreachMessage({ customerName, merchantName, amount, currency, channel, recoveryUrl, preferredLanguage }) {
  const systemPrompt = `
    You are the Outreach Copywriting Agent for RecoverAI.
    Generate a polite, empathetic, high-converting recovery message for a customer whose checkout was interrupted.
    Rules:
    - Tone: Helpful, professional, never aggressive or threatening.
    - Format: Concise message suitable for ${channel}.
    - Include the customer's name (${customerName}), merchant name (${merchantName}), amount (${currency} ${amount}), and payment link (${recoveryUrl}).
    - Language style: Natural Indian ${preferredLanguage || 'Hinglish'} or English as appropriate.
    - Return strict JSON with:
       - "headline": string,
       - "messageText": string,
       - "callToAction": string
  `;

  const userPrompt = JSON.stringify({ customerName, merchantName, amount, currency, channel, recoveryUrl, preferredLanguage });
  const aiResult = await callGemini(systemPrompt, userPrompt);

  if (aiResult && aiResult.messageText) {
    return aiResult;
  }

  // Contextual fallback template
  return {
    headline: `Incomplete Payment for ${merchantName}`,
    messageText: `Hi ${customerName}! We noticed your payment of ${currency} ${amount} to ${merchantName} couldn't be completed. If this was unexpected, you can complete it securely in 1-click here: ${recoveryUrl}\n\nIf you prefer to pay on another date, just reply with your convenient date!`,
    callToAction: 'Complete Payment Now'
  };
}

/**
 * AGENT 3: REALISTIC HINGLISH VOICE AGENT
 * Simulates a natural, conversational voice call in Hinglish with the customer,
 * listens to their response, and extracts a promise-to-pay commitment.
 */
export async function simulateHinglishVoiceCall({ customerName, merchantName, amount, currency, customerHistory, userResponseSimulation }) {
  const effectiveUserSpeech = userResponseSimulation || 'Haan bhaiya, payment jaldi complete kar dunga.';
  const todayIso = new Date().toISOString().slice(0, 10);

  const systemPrompt = `
    You are the Hinglish AI Voice Recovery Agent for RecoverAI.
    You speak in natural, friendly, polite Indian Hinglish (a mix of Hindi and English as commonly spoken in India).
    Today's reference date is: ${todayIso}.
    
    Context:
    - Customer Name: ${customerName}
    - Merchant: ${merchantName}
    - Amount Pending: ${currency} ${amount}
    - Customer just said: "${effectiveUserSpeech}"

    Your task:
    1. Listen carefully to what the customer said ("${effectiveUserSpeech}").
    2. Respond directly, respectfully, and empathetically to their specific explanation (e.g. if they say traveling, salary on Friday, bank limit, or request cancellation).
    3. If they commit to paying on a day/date, confirm you have scheduled a reminder for that date and will send a WhatsApp link.
    4. If they wish to cancel or dispute, acknowledge politely without arguing.
    5. Return strict JSON with:
       - "transcript": array of dialogue turns:
         [
           { "speaker": "Agent", "text": "Greeting line from agent" },
           { "speaker": "Customer", "text": "${effectiveUserSpeech}" },
           { "speaker": "Agent", "text": "Your direct, context-aware AI reply to what the customer said" }
         ],
       - "agentReply": string (exact text of your dynamic reply to the customer),
       - "extractedIntent": string ('promise_to_pay' | 'dispute' | 'already_paid' | 'cancellation_request'),
       - "promisedDate": string (computed ISO date YYYY-MM-DD, or null if no promise made),
       - "confidence": number (between 0.8 and 0.99),
       - "sentiment": string ('cooperative' | 'hesitant' | 'frustrated'),
       - "summary": string (brief 1-sentence English summary of the call)
  `;

  const userPrompt = JSON.stringify({ customerName, merchantName, amount, currency, customerHistory, userResponseSimulation: effectiveUserSpeech });
  const aiResult = await callGemini(systemPrompt, userPrompt);

  if (aiResult && aiResult.transcript && aiResult.extractedIntent) {
    // Ensure agentReply is always present for the frontend audio synthesizer
    if (!aiResult.agentReply && Array.isArray(aiResult.transcript)) {
      const agentMsgs = aiResult.transcript.filter(t => t.speaker === 'Agent');
      aiResult.agentReply = agentMsgs[agentMsgs.length - 1]?.text || '';
    }
    return aiResult;
  }

  // Dynamic heuristic fallback (computes actual dates & responses dynamically, never hardcoded)
  const lower = effectiveUserSpeech.toLowerCase();
  let intent = 'promise_to_pay';
  let sentiment = 'cooperative';
  let targetDate = new Date();
  let dateText = '2 din baad';

  if (lower.includes('cancel') || lower.includes('stop') || lower.includes('unsubscribe') || lower.includes('band')) {
    intent = 'cancellation_request';
    sentiment = 'frustrated';
    targetDate = null;
  } else if (lower.includes('dispute') || lower.includes('wrong') || lower.includes('nahi kiya')) {
    intent = 'dispute';
    sentiment = 'frustrated';
    targetDate = null;
  } else if (lower.includes('paid') || lower.includes('ho gaya') || lower.includes('done')) {
    intent = 'already_paid';
    sentiment = 'hesitant';
    targetDate = null;
  } else {
    // Compute dynamic date
    if (lower.includes('kal') || lower.includes('tomorrow')) {
      targetDate.setDate(targetDate.getDate() + 1);
      dateText = 'kal';
    } else if (lower.includes('friday') || lower.includes('shukrawar')) {
      const day = targetDate.getDay();
      const diff = (5 - day + 7) % 7 || 7;
      targetDate.setDate(targetDate.getDate() + diff);
      dateText = 'Friday ko';
    } else if (lower.includes('monday') || lower.includes('somwar')) {
      const day = targetDate.getDay();
      const diff = (1 - day + 7) % 7 || 7;
      targetDate.setDate(targetDate.getDate() + diff);
      dateText = 'Monday ko';
    } else {
      targetDate.setDate(targetDate.getDate() + 2);
      dateText = 'parso';
    }
  }

  const promisedIso = targetDate ? targetDate.toISOString().slice(0, 10) : null;
  let dynamicAgentReply = '';

  if (intent === 'cancellation_request') {
    dynamicAgentReply = `Hum samajh sakte hain ${customerName} ji. Maine aapka request record kar liya hai aur hum aage se aapko pareshan nahi karenge. Dhanyawaad!`;
  } else if (intent === 'dispute') {
    dynamicAgentReply = `Theek hai ${customerName} ji, humne aapka issue note kar liya hai. Hamari support team aapse verification ke liye sampark karegi. Thank you!`;
  } else if (intent === 'already_paid') {
    dynamicAgentReply = `Shukriya batane ke liye ${customerName} ji! Hum transaction records check kar lete hain. Agar payment confirm hota hai to reminder band ho jayega.`;
  } else {
    dynamicAgentReply = `Bilkul samajh sakta hoon ${customerName} ji! Main aapka payment ${dateText} ke liye schedule kar deta hoon aur direct link aapke WhatsApp par bhej raha hoon. Thank you!`;
  }

  return {
    transcript: [
      {
        speaker: 'Agent',
        text: `Namaste ${customerName} ji! Main ${merchantName} ki support team se bol raha hoon. Aapka ₹${amount} ka payment complete nahi ho paya tha, kya sab theek hai?`
      },
      {
        speaker: 'Customer',
        text: effectiveUserSpeech
      },
      {
        speaker: 'Agent',
        text: dynamicAgentReply
      }
    ],
    agentReply: dynamicAgentReply,
    extractedIntent: intent,
    promisedDate: promisedIso,
    confidence: 0.94,
    sentiment,
    summary: `Customer stated: "${effectiveUserSpeech}". Agent responded dynamically and scheduled next action for ${promisedIso || 'immediate review'}.`
  };
}

/**
 * AGENT 4: PROMISE & INTENT PARSER
 * Extracts intent and commitment dates from any customer reply text.
 */
export async function parseCustomerIntent(customerText) {
  const systemPrompt = `
    You are the Intent and Promise-to-Pay Extraction Agent.
    Analyze the customer's response text and determine:
    1. Intent: 'promise_to_pay', 'cancel_subscription', 'dispute', or 'unknown'
    2. Promised Date: If they commit to a date (e.g. 'tomorrow', 'Friday', '15th Sept', 'salary on 5th'), compute the target date in YYYY-MM-DD format based on today's reference date (${new Date().toISOString().slice(0, 10)}).
    Return strict JSON with:
    - "intent": string,
    - "promisedDate": string or null,
    - "confidence": number,
    - "reasoning": string
  `;

  const aiResult = await callGemini(systemPrompt, customerText);
  if (aiResult && aiResult.intent) {
    return aiResult;
  }

  // Regex and NLP heuristic fallback
  const lower = (customerText || '').toLowerCase();
  if (lower.includes('cancel') || lower.includes('stop') || lower.includes('unsubscribe')) {
    return {
      intent: 'cancel_subscription',
      promisedDate: null,
      confidence: 0.95,
      reasoning: 'Customer explicitly requested cancellation.'
    };
  }

  const dateMatch = customerText.match(/(\d{4}-\d{2}-\d{2})/);
  if (dateMatch) {
    return {
      intent: 'promise_to_pay',
      promisedDate: dateMatch[1],
      confidence: 0.96,
      reasoning: 'Found exact ISO date.'
    };
  }

  const targetDate = new Date(Date.now() + 2 * 24 * 60 * 60 * 1000).toISOString().slice(0, 10);
  return {
    intent: 'promise_to_pay',
    promisedDate: targetDate,
    confidence: 0.88,
    reasoning: 'Detected verbal commitment.'
  };
}
